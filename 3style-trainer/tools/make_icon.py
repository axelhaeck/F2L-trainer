"""Generates the launcher icon (development tool): an isometric cube wearing a blindfold.

Writes app/src/main/res/drawable/ic_launcher_foreground.xml and, with an argument, an SVG preview.
Coordinates: 108 x 108 adaptive icon viewport, everything inside the 66 dp safe circle.
"""
import math
import os
import sys

C = (57.0, 54.0)          # centre of the cube
S = 25.0                  # edge length in projection units
cos30 = math.cos(math.radians(30))


def P(x, y, z):
    """Isometric projection of the unit cube (centred): x to the right-front, z to the left-front, y up."""
    return (C[0] + (x - z) * cos30 * S, C[1] + ((x + z) * 0.5 - y) * S)


def face_point(face, u, v):
    """Point on a face, u, v in 0..1 (u along the row, v down)."""
    if face == "U":   # y = 1, u from left corner (x=0,z=1)... grid: u -> x, v -> z
        return P(u, 1, v)
    if face == "F":   # z = 1: u -> x, v down y
        return P(u, 1 - v, 1)
    if face == "R":   # x = 1: u -> -z (from front to back), v down
        return P(1, 1 - v, 1 - u)


def quad(face, u0, v0, u1, v1):
    return [face_point(face, u0, v0), face_point(face, u1, v0), face_point(face, u1, v1), face_point(face, u0, v1)]


def path(points):
    return "M" + " L".join("%.2f,%.2f" % p for p in points) + " Z"


shapes = []  # (colour, points, stroke)
# body (dark outline of the cube)
shapes.append(("#FF111111", [P(0, 1, 0), P(1, 1, 0), P(1, 0, 0), P(1, 0, 1), P(0, 0, 1), P(0, 1, 1)], None))
COL = {"U": "#FFFFFFFF", "F": "#FF00A651", "R": "#FFD0021B"}
gap = 0.045
for face in "UFR":
    for r in range(3):
        for c in range(3):
            shapes.append((COL[face], quad(face, c / 3 + gap, r / 3 + gap, (c + 1) / 3 - gap, (r + 1) / 3 - gap), None))

# blindfold: a black band around the middle row of the side faces, slightly wider than the row
b0, b1 = 0.30, 0.70
band_f = quad("F", -0.02, b0, 1.0, b1)
band_r = quad("R", 0.0, b0, 1.02, b1)
BAND = "#FF0B0B0E"
shapes.append((BAND, band_f, None))
shapes.append((BAND, band_r, None))
# light edge lines on the band so it reads as fabric on a dark cube
edge = "#FF5A606B"
# knot with two hanging, slightly waving tails at the left edge of the band
kx, ky = face_point("F", -0.02, (b0 + b1) / 2)
knot = [(kx - 2.2, ky - 3.4), (kx + 0.8, ky - 2.8), (kx + 0.8, ky + 2.8), (kx - 2.2, ky + 3.4)]
tail1 = [(kx - 1.5, ky - 2.0), (kx - 7.0, ky + 0.5), (kx - 12.5, ky + 4.5), (kx - 10.5, ky + 6.8), (kx - 5.5, ky + 3.6), (kx - 1.0, ky + 1.8)]
tail2 = [(kx - 1.6, ky + 0.2), (kx - 4.6, ky + 6.0), (kx - 5.6, ky + 12.5), (kx - 2.6, ky + 12.9), (kx - 1.8, ky + 7.0), (kx + 0.4, ky + 2.6)]
for t in (tail1, tail2, knot):
    shapes.append((BAND, t, None))

lines = []  # stroke lines (colour, points)
lines.append((edge, [face_point("F", -0.02, b0), face_point("F", 1.0, b0), face_point("R", 1.02, b0)]))
lines.append((edge, [face_point("F", -0.02, b1), face_point("F", 1.0, b1), face_point("R", 1.02, b1)]))


def vector_xml():
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/make_icon.py: a cube wearing a blindfold. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp"',
           '    android:viewportWidth="108" android:viewportHeight="108">']
    for col, pts, _ in shapes:
        out.append('    <path android:fillColor="%s" android:pathData="%s" />' % (col, path(pts)))
    for col, pts in lines:
        d = "M" + " L".join("%.2f,%.2f" % p for p in pts)
        out.append('    <path android:strokeColor="%s" android:strokeWidth="0.7" android:strokeLineJoin="round" android:pathData="%s" />' % (col, d))
    out.append('</vector>')
    return "\n".join(out) + "\n"


def svg(bg="#E8ECF3"):
    argb = lambda c: "#" + c[3:]
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">',
           '<rect width="108" height="108" fill="%s"/>' % bg,
           '<circle cx="54" cy="54" r="33" fill="none" stroke="#555" stroke-dasharray="1,1" stroke-width="0.3"/>']
    for col, pts, _ in shapes:
        out.append('<path fill="%s" d="%s"/>' % (argb(col), path(pts)))
    for col, pts in lines:
        out.append('<path fill="none" stroke="%s" stroke-width="0.7" stroke-linejoin="round" d="%s"/>' %
                   (argb(col), "M" + " L".join("%.2f,%.2f" % p for p in pts)))
    out.append('</svg>')
    return "\n".join(out)


if __name__ == "__main__":
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    with open(os.path.join(root, "app/src/main/res/drawable/ic_launcher_foreground.xml"), "w") as f:
        f.write(vector_xml())
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w") as f:
            f.write(svg())
